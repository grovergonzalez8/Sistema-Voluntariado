export async function createI18n(): Promise<i18n> {
  const instance = i18next.createInstance();
  await instance.use(initReactI18next).init({
    fallbackLng: 'es',
    interpolation: { escapeValue: false },
    lng: 'es',
    resources,
  });
  return instance;
}
